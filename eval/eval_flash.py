"""Evaluate the flash detector on generated samples.

Usage (from the repo root):
    python -m eval.eval_flash benchmark/data/*

Every sample is scored: samples with a labeled flash should produce one finding near the label;
samples without one (clean flash app, and the focus app) should produce none. Findings are
mapped to the key-log clock with the sample's clock-sync offset (from labels.json "qa" if
present, else estimated with the pipeline's own sync).

Read the numbers with care: this is the synthetic set only, generated by the same author as
the detector, so good scores are a smoke test, not evidence of real-world accuracy.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from a11y_replay.config import DEFAULT
from a11y_replay.detectors.flash import detect_flashes
from a11y_replay.taxonomy import IssueType
from eval.common import sample_offset
from eval.metrics import match_events, prf


def main(paths: list[str]) -> None:
    samples = [Path(p) for p in paths if (Path(p) / "labels.json").exists()]
    if not samples:
        raise SystemExit("No samples found. Pass sample directories, e.g. benchmark/data/*")
    print(f"{'sample':28} {'labeled':>8} {'found':>6} {'TP':>3} {'FP':>3} {'FN':>3}  onset error (s)")
    TP = FP = FN = 0
    untrusted = []
    for s in samples:
        meta = json.loads((s / "labels.json").read_text())
        video = next(s.glob("video.*"))
        offset, ok = sample_offset(s, meta, video)
        if not ok:
            untrusted.append(s.name)
        found = detect_flashes(video, DEFAULT, offset=offset)
        pred = [f.start for f in found]
        true = [l["t"] for l in meta["labels"] if l["issue_type"] == IssueType.FLASHING.value]
        tp, fp, fn = match_events(pred, true)
        errs = [min(pred, key=lambda p: abs(p - t)) - t for t in true
                if pred and abs(min(pred, key=lambda p: abs(p - t)) - t) <= DEFAULT.time_tolerance_s]
        err = ", ".join(f"{e:+.2f}" for e in errs) or "-"
        print(f"{s.name:28} {len(true):8d} {len(found):6d} {tp:3d} {fp:3d} {fn:3d}  {err}")
        TP, FP, FN = TP + tp, FP + fp, FN + fn
    p, r, f1 = prf(TP, FP, FN)
    print(f"\nTotal over {len(samples)} samples: TP={TP} FP={FP} FN={FN}  "
          f"precision={p:.2f} recall={r:.2f} F1={f1:.2f}")
    if untrusted:
        print("Clock sync NOT trusted for (offset 0 or estimate used anyway):", ", ".join(untrusted))


if __name__ == "__main__":
    main(sys.argv[1:])